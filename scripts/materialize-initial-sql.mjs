// Narrow mechanical SQL transcription of this repository's scalar-only contract.
// Does NOT execute Prisma install scripts or replace the pending Prisma diff gate.
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const source=readFileSync('contracts/schema.prisma','utf8');
const quote=x=>'"'+x.replaceAll('"','""')+'"';
const name=x=>x.length<=63?x:x.slice(0,50)+'_'+createHash('sha256').update(x).digest('hex').slice(0,12);
const enums=[...source.matchAll(/enum (\w+)\s*\{([^}]+)\}/g)];
const enumNames=new Set(enums.map(x=>x[1]));
const sql=['-- Initial scalar schema transcribed from the supplied Prisma contract.',
  '-- Generated by scripts/materialize-initial-sql.mjs, NOT by the Prisma CLI.',
  '-- Pending Prisma-engine diff verification; tested in embedded PostgreSQL.',
  '-- UUIDs and @updatedAt values are supplied by application code, as in Prisma.'];
for(const [,key,body] of enums)sql.push(`CREATE TYPE ${quote(key)} AS ENUM (${body.trim().split(/\s+/).map(x=>"'"+x+"'").join(', ')});`);
const indices=[];
for(const [,model,body] of source.matchAll(/model (\w+)\s*\{([^}]+)\}/g)){
  const cols=[],keys=[];
  for(const text of body.trim().split('\n')){
    const line=text.trim();if(!line||line.startsWith('//'))continue;
    if(line.startsWith('@@')){
      const d=line.match(/^@@(id|unique|index)\(\[([^\]]+)\]\)$/);if(!d)throw new Error('Unsupported declaration '+line);
      const fields=d[2].split(',').map(x=>x.trim());
      if(d[1]==='id')keys.push(`CONSTRAINT ${quote(name(model+'_pkey'))} PRIMARY KEY (${fields.map(quote).join(',')})`);
      else indices.push(`CREATE ${d[1]==='unique'?'UNIQUE ':''}INDEX ${quote(name(model+'_'+fields.join('_')+(d[1]==='unique'?'_key':'_idx')))} ON ${quote(model)} (${fields.map(quote).join(',')});`);
      continue;
    }
    const f=line.match(/^(\w+)\s+(\w+)(\?|\[\])?\s*(.*)$/);if(!f)throw new Error('Unsupported field '+line);
    const [,field,type,modifier,attrs]=f;let dbtype;
    const native=attrs.match(/@db\.(\w+)(?:\(([^)]+)\))?/);
    if(native){const types={Uuid:'UUID',VarChar:'VARCHAR',Timestamptz:'TIMESTAMPTZ',Decimal:'DECIMAL'};dbtype=types[native[1]];if(!dbtype)throw new Error('Unsupported native '+line);if(native[2])dbtype+='('+native[2]+')';}
    else dbtype=({String:'TEXT',Int:'INTEGER',Boolean:'BOOLEAN',Json:'JSONB',DateTime:'TIMESTAMP(3)',Decimal:'DECIMAL(65,30)'})[type]||(enumNames.has(type)?quote(type):null);
    if(!dbtype)throw new Error('Unsupported type '+line);
    if(modifier==='[]')dbtype+='[]';
    let col=quote(field)+' '+dbtype+(modifier==='?'?'':' NOT NULL');
    const def=attrs.match(/@default\(("[^"]*"|[-\d.]+|true|false|\w+\(\)|\w+)\)/);
    if(def){const d=def[1];if(d==='now()')col+=' DEFAULT CURRENT_TIMESTAMP';else if(d==='uuid()'){}else if(d.startsWith('"'))col+=" DEFAULT '"+JSON.parse(d).replaceAll("'","''")+"'";else if(/^[-\d.]+$|^(true|false)$/.test(d))col+=' DEFAULT '+d;else if(enumNames.has(type))col+=" DEFAULT '"+d+"'";else throw new Error('Unsupported default '+line);}
    if(/@id\b/.test(attrs))keys.push(`CONSTRAINT ${quote(name(model+'_pkey'))} PRIMARY KEY (${quote(field)})`);
    if(/@unique\b/.test(attrs))indices.push(`CREATE UNIQUE INDEX ${quote(name(model+'_'+field+'_key'))} ON ${quote(model)} (${quote(field)});`);
    cols.push(col);
  }
  sql.push(`CREATE TABLE ${quote(model)} (\n  ${[...cols,...keys].join(',\n  ')}\n);`);
}
sql.push(...indices);
mkdirSync('prisma/migrations/202609100001_initial',{recursive:true});
writeFileSync('prisma/migrations/202609100001_initial/migration.sql',sql.join('\n\n')+'\n');
mkdirSync('prisma/migrations/202609100002_constraints',{recursive:true});
writeFileSync('prisma/migrations/202609100002_constraints/migration.sql',readFileSync('contracts/required-constraints.sql','utf8'));
console.log('Initial SQL and unchanged constraints materialized. Prisma CLI verification remains pending.');
